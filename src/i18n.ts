import type { Language } from './types';

export function getTodayIso(): string {
  const d = new Date();
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

export function formatReadableDate(dateStr: string, lang: Language): string {
  const [y, m, d] = dateStr.split('-').map(Number);
  if (!y || !m || !d) return dateStr;
  const dateObj = new Date(y, m - 1, d);
  return dateObj.toLocaleDateString(lang === 'hi' ? 'hi-IN' : 'en-IN', {
    weekday: 'short',
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  });
}

export function formatTime(isoString: string | null, lang: Language): string {
  if (!isoString) return '';
  return new Date(isoString).toLocaleTimeString(lang === 'hi' ? 'hi-IN' : 'en-IN', {
    hour: '2-digit',
    minute: '2-digit',
    hour12: true,
  });
}

export function buildWhatsAppMessage(
  hostelName: string,
  dateStr: string,
  link: string,
  lang: Language
): string {
  const formattedDate = formatReadableDate(dateStr, lang);
  if (lang === 'hi') {
    return `*${hostelName} — उपस्थिति (${formattedDate})*\nकृपया नीचे दिए गए लिंक को खोलकर अपनी उपस्थिति (Present / Absent) दर्ज करें:\n${link}`;
  }
  return `*${hostelName} — Attendance (${formattedDate})*\nPlease open the link below to mark your attendance (Present / Absent):\n${link}`;
}

